const nomes = ['ana Julia', 'Caio vinicius', 'BIA silva'];

// Upper Case

const nomesPadronizadosUpper = nomes.map((nome) => nome.toUpperCase());
console.log('toUpperCase:', nomesPadronizadosUpper);

// Lower Case
const nomesPadronizadoLower = nomes.map((nome) => nome.toLowerCase());
console.log('toLowerCase:', nomesPadronizadoLower);
